def read(path):
    with open(path, 'r', encoding='utf-8') as f:
        return f.read()

def read_json(path):
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)

def js_str(s):
    """Escape a string for embedding in a JS template literal."""
    return s.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')

